"""Provided: checks on your evaluation runs in logs/runs.jsonl.

These fail until you have run your evaluation and committed the log.
Do not edit this file.
"""

import json
from pathlib import Path

ROOT = Path(__file__).parent.parent
LOG = ROOT / "logs" / "runs.jsonl"
TASKS = ROOT / "docs" / "tasks.txt"


def tasks() -> list[str]:
    """The evaluation tasks, one per line."""
    if not TASKS.exists():
        return []
    lines = TASKS.read_text().splitlines()
    return [line.strip() for line in lines if line.strip()]


def runs() -> list[dict]:
    """The logged runs of the evaluation tasks."""
    if not LOG.exists():
        return []
    rows = [json.loads(line) for line in LOG.read_text().splitlines() if line]
    return [row for row in rows if row["task"] in tasks()]


def test_six_tasks_are_listed() -> None:
    """docs/tasks.txt holds six or more tasks, with no TODO left."""
    assert len(tasks()) >= 6
    assert not any("TODO" in task for task in tasks())


def test_each_task_ran_three_times_each_way() -> None:
    """Three team runs and three single-agent runs of each task."""
    assert tasks(), "docs/tasks.txt lists no tasks"
    for task in tasks():
        for design in ("team", "single"):
            done = [
                r for r in runs() if r["task"] == task and r["design"] == design
            ]
            assert len(done) >= 3, (design, task)


def test_a_team_run_used_more_than_one_agent() -> None:
    """In a team run, a second agent was called or handed the task."""
    assert any(
        len(r["agents_at_work"]) >= 2 for r in runs() if r["design"] == "team"
    )


def test_a_person_declined_a_change() -> None:
    """A person refused an approval at least once."""
    assert any(not a["approved"] for r in runs() for a in r["approvals"])


def test_a_guardrail_rejected_a_call() -> None:
    """A tool result reported an error at least once."""
    assert any(
        "error" in step["text"].lower()
        for r in runs()
        for step in r["steps"]
        if step["kind"] == "result"
    )
